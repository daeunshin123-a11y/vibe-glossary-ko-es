// ─────────────────────────────────────────────────────────────
// 🌱 기여 등급
//
// 번역 + 댓글을 몇 개 남겼는지에 따라 별명 앞에 이모지가 붙습니다.
// 많이 참여할수록 새싹이 자라나는 모양입니다.
// ─────────────────────────────────────────────────────────────

export const 등급표 = [
  { 최소: 21, 이모지: "👑", 이름: "왕관" },
  { 최소: 11, 이모지: "🌟", 이름: "별" },
  { 최소: 6, 이모지: "🌳", 이름: "나무" },
  { 최소: 3, 이모지: "🌿", 이름: "잎새" },
  { 최소: 1, 이모지: "🌱", 이름: "새싹" },
] as const;

export function 등급구하기(개수: number) {
  return 등급표.find((단계) => 개수 >= 단계.최소) ?? null;
}

/** 별명 앞에 붙일 이모지. 아직 활동이 없으면 빈 문자열 */
export function 등급이모지(기여도: Record<string, number>, 별명: string) {
  const 개수 = 기여도[별명] ?? 0;
  return 등급구하기(개수)?.이모지 ?? "";
}
