// ─────────────────────────────────────────────────────────────
// 🌎 지역
//
// 더빙·자막은 한 나라만 보는 게 아닙니다.
// 멕시코 표현을 쓰면 아르헨티나 시청자가 어색해하고,
// 스페인 표현을 쓰면 중남미 전체가 낯설어합니다.
//
// 그래서 "이 번역이 어디서 통하는 말인지" 를 함께 적어둡니다.
// (7주차 리서치 에이전트도 같은 목록을 씁니다)
// ─────────────────────────────────────────────────────────────

export const 지역목록 = [
  { 값: "중립", 이모지: "🌎", 이름: "중립", 설명: "어느 나라에서나 통하는 표현" },
  { 값: "멕시코", 이모지: "🇲🇽", 이름: "멕시코", 설명: "멕시코에서 주로 씀" },
  { 값: "스페인", 이모지: "🇪🇸", 이름: "스페인", 설명: "스페인에서 주로 씀" },
  { 값: "아르헨티나", 이모지: "🇦🇷", 이름: "아르헨티나", 설명: "아르헨티나에서 주로 씀" },
  { 값: "콜롬비아", 이모지: "🇨🇴", 이름: "콜롬비아", 설명: "콜롬비아에서 주로 씀" },
] as const;

export function 지역찾기(값: string | null | undefined) {
  if (!값) return null;
  return 지역목록.find((지역) => 지역.값 === 값) ?? null;
}

export function 올바른지역인가(값: string) {
  return 지역목록.some((지역) => 지역.값 === 값);
}
