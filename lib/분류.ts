// 사전에 그냥 안 나오는 말들을 "왜 번역하기 어려운지"로 나눕니다.
// 값이 비어 있으면 '미분류'입니다.
// ─────────────────────────────────────────────────────────────

export const 분류목록 = [
  { 값: "문화", 이모지: "🌏", 이름: "문화", 설명: "한국에만 있는 개념·제도·호칭" },
  { 값: "신조어", 이모지: "🔥", 이름: "신조어", 설명: "사전에 없는 요즘 말" },
  { 값: "비속어", 이모지: "🤬", 이름: "비속어", 설명: "욕·거친 말. 강도를 메모에 적어주세요" },
] as const;

export function 분류찾기(값: string | null) {
  if (!값) return null;
  return 분류목록.find((분류) => 분류.값 === 값) ?? null;
}
