// 🎲 별명 뽑기
//
// 실명 대신 쓸 별명을 무작위로 만들어 줍니다.
// "형용사 + 사물/동물" 조합이라 귀엽고, 실명이 드러나지 않습니다.
// ─────────────────────────────────────────────────────────────

const 형용사 = [
  "우울한", "신난", "졸린", "배고픈", "수줍은", "용감한", "느긋한", "재빠른",
  "엉뚱한", "다정한", "꼼꼼한", "나른한", "씩씩한", "새침한", "상냥한", "발랄한",
  "무뚝뚝한", "궁금한", "심심한", "설레는", "차분한", "부지런한", "덤덤한", "말많은",
];

const 명사 = [
  "리코더", "짱돌", "고양이", "문어", "수달", "오징어", "감자", "붕어빵",
  "라디오", "우산", "자몽", "두더지", "참새", "만두", "코끼리", "해파리",
  "젤리", "양말", "달팽이", "고등어", "선인장", "주전자", "복숭아", "너구리",
];

export function 별명뽑기() {
  const ㄱ = 형용사[Math.floor(Math.random() * 형용사.length)];
  const ㄴ = 명사[Math.floor(Math.random() * 명사.length)];
  return ㄱ + ㄴ;
}
